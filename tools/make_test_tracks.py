# Synthetic click tracks at odd tempos to validate the tempo map, loop points and decoder alignment.
import numpy as np, subprocess, json, os, sys
SR = 44100
def track(bpm, bars, lead, name, f0):
    beat = 60 / bpm; n = int(SR * (lead + bars * 4 * beat + 1.0))
    x = np.zeros(n, np.float32)
    for b in range(bars * 4):
        t = lead + b * beat; i = int(round(t * SR))
        acc = 1.0 if b % 4 == 0 else 0.45
        L = int(0.09 * SR); k = np.arange(L)
        click = np.sin(2 * np.pi * (f0 * (2 if b % 4 == 0 else 1.5)) * k / SR) * np.exp(-k / (0.012 * SR)) * acc * 0.6
        x[i:i + L] += click[: max(0, min(L, n - i))]
        # a soft drone so loops are audible
    t = np.arange(n) / SR
    x += 0.05 * np.sin(2 * np.pi * f0 / 2 * t) * (t > lead)
    st = np.stack([x, x * 0.9], 1)
    os.makedirs('dist/music', exist_ok=True)
    wav = f'/tmp/{name}.wav'
    import soundfile as sf; sf.write(wav, st, SR)
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', wav, '-codec:a', 'libmp3lame', '-b:a', '96k', f'dist/music/{name}.mp3'], check=True)
    first = lead  # the first click starts exactly on the first downbeat
    return {'slot': name, 'url': f'music/{name}.mp3', 'bpm': bpm, 'offset': lead, 'loop': [0, bars], 'first': first, 'th': 0.05, 'gain': 0.5, 'transpose': 0}
T = [track(80, 8, 0.3, 'calm', 440), track(92, 12, 0.42, 'stage1', 520), track(132, 16, 0.1, 'stage2', 600), track(108, 16, 0.25, 'stage3', 480), track(140, 8, 0.2, 'boss', 380), track(76, 8, 0.2, 'ending', 400)]
T.append({'slot': 'tutor', 'alias': 'calm'})
open('src/tracks.js', 'w').write('// generated by tools/make_test_tracks.py (synthetic test tracks)\nexport const TRACKS = ' + json.dumps(T, indent=1) + ';\n')
print('ok', [t['slot'] for t in T])
